const FOX_TIMELINE_IDS = new Set([
  "x-men",
  "x2-x-men-united",
  "x-men-days-of-future-past",
  "x-men-the-last-stand",
]);

const TVA_IDS = new Set([
  "loki-season-1",
  "loki-season-2",
]);

const MULTIVERSE_IDS = new Set([
  "spider-man-no-way-home",
  "doctor-strange-multiverse-of-madness",
  "deadpool-and-wolverine",
  "the-fantastic-four-first-steps",
]);

function getTimelineGroup(
  movie: Omit<Movie, "timelineGroup" | "timelineTags">
): TimelineGroup {
  return FOX_TIMELINE_IDS.has(movie.id) ? "fox" : "mcu";
}

function getTimelineTags(
  movie: Omit<Movie, "timelineGroup" | "timelineTags">
): TimelineTag[] {
  const tags: TimelineTag[] = [];

  if (TVA_IDS.has(movie.id)) {
    tags.push("tva");
  }

  if (MULTIVERSE_IDS.has(movie.id)) {
    tags.push("multiverse");
  }

  return tags;
}

export const movies: Movie[] = rawMovies.map((movie) => ({
  ...movie,
  storyOrder: STORY_ORDER[movie.id] ?? movie.storyOrder,
  timelineGroup: getTimelineGroup(movie),
  timelineTags: getTimelineTags(movie),
}));


const missingStoryOrders = rawMovies.filter(
  (movie) => !(movie.id in STORY_ORDER)
);

if (missingStoryOrders.length > 0) {
  console.error(
    "Missing story orders:",
    missingStoryOrders.map((movie) => movie.id)
  );
}
